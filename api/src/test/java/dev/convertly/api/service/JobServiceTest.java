package dev.convertly.api.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.inOrder;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import dev.convertly.api.entity.ConversionJob;
import dev.convertly.api.exception.FileNotUploadedException;
import dev.convertly.api.exception.FileTooLargeException;
import dev.convertly.api.repository.ConversionJobRepository;
import dev.convertly.common.ConversionMessage;
import dev.convertly.common.Format;
import dev.convertly.common.JobStatus;
import dev.convertly.common.Queues;
import java.util.Optional;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InOrder;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.amqp.rabbit.core.RabbitTemplate;
import org.springframework.test.util.ReflectionTestUtils;

@ExtendWith(MockitoExtension.class)
class JobServiceTest {

  private static final long MAX_FILE_SIZE = 10 * 1024 * 1024;

  @Mock private ConversionJobRepository repository;

  @Mock private StorageService storageService;

  @Mock private RabbitTemplate rabbitTemplate;

  @InjectMocks private JobService jobService;

  private UUID jobId;
  private ConversionJob job;

  @BeforeEach
  void setUp() {
    jobId = UUID.randomUUID();

    job = new ConversionJob(Format.PNG, Format.PDF, "image.png", 1024L);

    // Simulate the ID generated by the database.
    ReflectionTestUtils.setField(job, "id", jobId);

    job.assignInputKey("jobs/" + jobId + "/input");

    when(repository.findById(jobId)).thenReturn(Optional.of(job));
  }

  @Test
  void start_shouldQueueJobAndSendMessage_whenFileExists() {
    // Arrange
    when(storageService.sizeOf(job.getInputKey())).thenReturn(Optional.of(MAX_FILE_SIZE));

    // Act
    jobService.start(jobId);

    // Assert: job status
    assertEquals(JobStatus.QUEUED, job.getJobStatus());

    // Assert: job is saved before the message is sent
    InOrder inOrder = inOrder(repository, rabbitTemplate);

    inOrder.verify(repository).save(job);
    inOrder
        .verify(rabbitTemplate)
        .convertAndSend(org.mockito.ArgumentMatchers.eq(Queues.JOBS), any(ConversionMessage.class));

    // Assert: message content
    ArgumentCaptor<ConversionMessage> messageCaptor =
        ArgumentCaptor.forClass(ConversionMessage.class);

    verify(rabbitTemplate)
        .convertAndSend(org.mockito.ArgumentMatchers.eq(Queues.JOBS), messageCaptor.capture());

    ConversionMessage message = messageCaptor.getValue();

    assertEquals(jobId, message.jobId());
    assertEquals(job.getInputKey(), message.inputKey());
    assertEquals("jobs/" + jobId + "/output.pdf", message.outputKey());
    assertEquals(Format.PNG, message.from());
    assertEquals(Format.PDF, message.to());
  }

  @Test
  void start_shouldThrowFileNotUploadedException_whenFileDoesNotExist() {
    // Arrange
    when(storageService.sizeOf(job.getInputKey())).thenReturn(Optional.empty());

    // Act & Assert
    assertThrows(FileNotUploadedException.class, () -> jobService.start(jobId));

    // No message should be sent
    verify(rabbitTemplate, never()).convertAndSend(any(String.class), any(Object.class));

    // Job should not be saved
    verify(repository, never()).save(any(ConversionJob.class));

    // Job status should remain unchanged
    assertEquals(JobStatus.PENDING, job.getJobStatus());
  }

  @Test
  void start_shouldThrowFileTooLargeException_whenFileExceeds10MB() {
    // Arrange
    when(storageService.sizeOf(job.getInputKey())).thenReturn(Optional.of(MAX_FILE_SIZE + 1));

    // Act & Assert
    assertThrows(FileTooLargeException.class, () -> jobService.start(jobId));

    // No message should be sent
    verify(rabbitTemplate, never()).convertAndSend(any(String.class), any(Object.class));

    // Job should not be saved
    verify(repository, never()).save(any(ConversionJob.class));

    // Job status should remain unchanged
    assertEquals(JobStatus.PENDING, job.getJobStatus());
  }
}
